// ValeaPlopului1972 2.0.0 — Arhivă: cronologie din dosar, plan al urmelor, contribuții locale exportabile.
import {open, check, summary} from "./_lib.mjs";
const {browser, page, st} = await open("index", {lang: "ro", w: 1100, h: 800});
await page.evaluate(() => window.setMode("ext"));
await page.waitForTimeout(1500);
await page.evaluate(() => window.toggleDosar());
await page.waitForTimeout(500);
console.log("1. tab și cronologie");
await page.click("#dt2");
check("tabul Arhivă activ", await page.evaluate(() => document.getElementById("dp2").classList.contains("on") && document.getElementById("dt2").getAttribute("aria-selected") === "true"));
check("tab-urile 0 și 1 dezactivate", await page.evaluate(() => !document.getElementById("dp0").classList.contains("on") && !document.getElementById("dp1").classList.contains("on")));
const ys = await page.$$eval("#arh-list .arh-ev", e => e.map(x => +x.dataset.y));
check("5 evenimente din dosar, sortate cronologic", ys.length === 5 && ys.every((y, i) => !i || y >= ys[i - 1]), ys);
check("fiecare eveniment are sursa indicată", (await page.$$eval("#arh-list .src", e => e.every(x => x.textContent.length > 20))));
check("cronologie SVG cu etichete an", (await page.$$eval("#arh-tl svg text", t => t.map(x => x.textContent))).includes("1972"));
check("textul nu conține cheile brute", !/arh_/.test(await page.textContent("#dp2")));
check("planul: 3 tălpici + cerc de bază + corp", (await page.$$eval("#arh-plan svg polygon", e => e.length)) === 3 && (await page.$$eval("#arh-plan svg circle", e => e.length)) === 2);
check("planul are aria-label și avertisment despre ce nu e reprezentat", /nu este precizată/.test(await page.textContent("#arh-plan")) && !!(await page.getAttribute("#arh-plan svg", "aria-label")));
console.log("2. contribuții");
await page.click("#arh-add");
check("gol: nu salvează", (await page.evaluate(() => window._arh.load().length)) === 0);
await page.fill("#arh-y", "1973"); await page.fill("#arh-ti", "Notă <b>test</b>"); await page.fill("#arh-tx", "Text <img src=x onerror=alert(1)> propriu"); await page.fill("#arh-sr", "Martor, comunicare personală");
await page.click("#arh-add");
const L = await page.evaluate(() => window._arh.load());
check("salvată local cu prefix valeaplopului1972.", L.length === 1 && L[0].y === 1973 && (await page.evaluate(() => !!localStorage.getItem("valeaplopului1972.arhiva"))), L);
check("XSS: markup-ul apare ca text, nu se execută", (await page.$$eval("#arh-mine img, #arh-mine b", e => e.length)) === 0 && /<b>test<\/b>/.test(await page.textContent("#arh-mine")));
check("contribuția e marcată neverificată și apare în cronologie", /neverificată/.test(await page.textContent("#arh-list .mine")) && (await page.$$eval("#arh-list .arh-ev", e => e.length)) === 6);
await page.fill("#arh-ti", "Fără sursă"); await page.click("#arh-add");
check("fără sursă: marcată „fără sursă indicată”", /fără sursă indicată/.test(await page.textContent("#arh-mine")));
const [d1] = await Promise.all([page.waitForEvent("download"), page.click("#arh-exj")]);
const j = JSON.parse(await (await import("node:fs")).promises.readFile(await d1.path(), "utf8"));
check("export JSON: schema 1, 2 elemente", j.schema === 1 && j.items.length === 2 && j.app === "ValeaPlopului1972", j);
const [d2] = await Promise.all([page.waitForEvent("download"), page.click("#arh-ext")]);
check("export TXT conține titlul", /Fără sursă/.test(await (await import("node:fs")).promises.readFile(await d2.path(), "utf8")));
const raw = await page.evaluate(() => JSON.parse(localStorage.getItem("valeaplopului1972.arhiva")));
check("persistă în localStorage (2) și în listă", raw.length === 2 && (await page.$$eval("#arh-mine .arh-ev", e => e.length)) === 2);
await page.click("#arh-mine .arh-del >> nth=0");
await page.click(".fff-primary");
await page.waitForTimeout(300);
check("ștergere cu dialog propriu", (await page.$$eval("#arh-mine .arh-ev", e => e.length)) === 1);
console.log("3. limbă și robustețe");
await page.evaluate(() => localStorage.setItem("valeaplopului1972.arhiva", "{rupt"));
check("JSON corupt → listă goală, fără eroare", (await page.evaluate(() => window._arh.load().length)) === 0);
await page.evaluate(() => { setLang("en"); });
await page.waitForTimeout(300);
check("engleză: tab și titlu traduse", /ARCHIVE/.test(await page.textContent("#dt2")) && /Timeline/.test(await page.textContent("#dp2")));
await page.evaluate(() => { setLang("fr"); }); await page.waitForTimeout(200);
check("franceză: revine la engleză (fără română)", /Timeline/.test(await page.textContent("#dp2")));
check("fără depășire orizontală", (await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)) <= 0);
check("0 erori JS", st.errs.length === 0, st.errs);
check("0 cereri de rețea", st.net.length === 0, st.net);
check("0 violări CSP", (await page.evaluate(() => window.__csp)).length === 0);
await browser.close();
summary();
